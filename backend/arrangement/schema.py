def layer_meta(source_id: str) -> dict[str, Any]:
    """Taxonomy entry, with a sensible fallback for discovered layers."""
    if source_id in LAYER_TAXONOMY:
        return dict(LAYER_TAXONOMY[source_id])
    if source_id in DEFAULT_STEM_META:
        m = dict(DEFAULT_STEM_META[source_id])
        return {
            "family": m["family"],
            "label": m["label"],
            "color": {"vocals": "#ff5d8f", "drums": "#ff4534", "bass": "#3d7bff",
                      "harmony": "#2fd6a4", "unknown": "#85929e"}[m["family"]],
            "order": 130,
        }
    return {"family": "unknown", "label": source_id.replace("_", " ").title(),
            "color": "#85929e", "order": 130}


