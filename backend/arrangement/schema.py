class EnergyModel(BaseModel):
    """Two energy views: measured, and a musical proxy for felt intensity."""

    frame_hz: float = 20.0
    raw: Curve | None = None
    perceived: Curve | None = None
    components: dict[str, Curve] = Field(default_factory=dict)
    weights: dict[str, float] = Field(default_factory=dict)
    model_notes: str = ""
    norm_lo: float = 0.0
    norm_hi: float = 1.0

    def at(self, t: float, perceived: bool = True) -> float:
        c = self.perceived if perceived else self.raw
        return c.at(t) if c else float("nan")


