class BeatGrid(BaseModel):
    bpm: float = 0.0
    bpm_confidence: float = 0.0
    bpm_curve: list[tuple[float, float]] = Field(default_factory=list)  # (t, bpm)
    beats: list[float] = Field(default_factory=list)
    downbeats: list[int] = Field(default_factory=list)  # indices into beats
    meter: str = "4/4"
    meter_confidence: float = 0.0
    offset_seconds: float = 0.0  # time of first downbeat
    first_bar: float = 0.0  # grid time of bar 0
    beat_grid_confidence: float = 0.0
    method: str = "librosa"
    onset_times: list[float] = Field(default_factory=list)
    onset_strength: list[float] = Field(default_factory=list)
    tempo_drift: float = 0.0  # bpm spread
    is_tangent: bool = False  # no stable pulse
    metrical_confidence: float = 0.0

    def beat_at(self, t: float) -> float | None:
        import bisect

        if not self.beats:
            return None
        i = bisect.bisect_left(self.beats, t)
        if i == 0:
            return self.beats[0]
        if i >= len(self.beats):
            return self.beats[-1]
        a, b = self.beats[i - 1], self.beats[i]
        if b <= a:
            return a
        frac = (t - a) / (b - a)
        return a + frac * (b - a)

    def bar_index(self, t: float) -> int:
        b = self.beat_at(t)
        if b is None or not self.bpm:
            return 0
        beats_per_bar = 4.0
        try:
            a, d = self.meter.split("/")
            beats_per_bar = float(a) / max(1.0, math.sqrt(float(d)))
        except Exception:
            pass
        return int(math.floor((b - self.offset_seconds) / (60.0 / self.bpm * beats_per_bar)))

    def time_of_bar(self, bar: int) -> float:
        if not self.bpm:
            return 0.0
        beats_per_bar = 4.0
        try:
            a, d = self.meter.split("/")
            beats_per_bar = float(a) / max(1.0, math.sqrt(float(d)))
        except Exception:
            pass
        return self.offset_seconds + bar * (60.0 / self.bpm * beats_per_bar)

    def time_of_beat(self, beat: int) -> float:
        if not self.bpm:
            return 0.0
        return self.offset_seconds + beat * (60.0 / self.bpm)

    def to_bar_beat(self, t: float) -> tuple[int, float]:
        b = self.beat_at(t)
        if b is None or not self.bpm:
            return 0, 0.0
        spb = 60.0 / self.bpm
        beats_from_zero = (b - self.offset_seconds) / spb
        return int(math.floor(beats_from_zero / 4.0)), (beats_from_zero % 4.0)


