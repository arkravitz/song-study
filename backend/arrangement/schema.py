class ActivitySegment(BaseModel):
    """A contiguous span where a source is measurably playing."""

    start: float
    end: float
    level_db: float = -70.0  # mean RMS dBFS inside the span
    peak_db: float = -70.0
    confidence: float = 0.6
    intensity: float = 0.0  # 0..1 normalised loudness within the song
    onset_slope_db_s: float = 0.0
    offset_slope_db_s: float = 0.0
    pan: float = 0.0  # -1..+1
    width: float = 0.0  # 0..1
    band_profile: dict[str, float] = Field(default_factory=dict)


class SourceDescriptor(BaseModel):
    """Timbre / production-role description derived from measurement."""

    # spectral
    spectral_centroid_hz: float | None = None
    spectral_rolloff85_hz: float | None = None
    spectral_flatness: float | None = None
    brightness_percentile: float | None = None
    # temporal
    attack_ms: float | None = None
    decay_ms: float | None = None
    sustain_ratio: float | None = None
    # articulation / play style
    is_percussive: float | None = None  # H/P ratio 0..1
    harmonicity: float | None = None
    # level & space
    rms_db: float | None = None
    crest_factor_db: float | None = None
    mean_pan: float | None = None
    mean_width: float | None = None
    reverb_ratio: float | None = None
    # register (for pitched sources)
    median_f0_hz: float | None = None
    f0_range_semitones: float | None = None
    # description
    role: str | None = None  # "rhythmic bed", "counter-melody", ...
    descriptors: list[str] = Field(default_factory=list)  # human phrases
    tags: list[tuple[str, float]] = Field(default_factory=list)  # (label, score)


class Source(BaseModel):
    """One musical layer."""

    id: str
    label: str
    family: SourceFamily = SourceFamily.UNKNOWN
    color: str = "#85929e"

    # where it came from
    origin: Literal["stem", "subdivision", "discovered", "inferred"] = "stem"
    stem_key: str | None = None  # which separated stem it lives in
    parent_id: str | None = None
    separator_model: str | None = None

    # what it is
    confidence: float = 0.5
    detection_method: str = "separator"
    descriptor: SourceDescriptor = Field(default_factory=SourceDescriptor)

    # when it plays
    segments: list[ActivitySegment] = Field(default_factory=list)
    active_bars: list[int] = Field(default_factory=list)

    # spatial
    pan_curve_ref: str | None = None
    mean_pan: float = 0.0
    mean_width: float = 0.0
    pan_stability: float = 0.0  # 1 = rock-steady, 0 = constantly moving

    # stats
    total_active_seconds: float = 0.0
    duty_cycle: float = 0.0  # fraction of song time active
    mean_level_db: float = -70.0
    max_level_db: float = -70.0
    n_entries: int = 0
    n_exits: int = 0
    #: True when the separated stem carries no audible instrument — a separator
    #: returns a file per instrument whether or not the track has one, and the
    #: empty file holds bleed. A silent source must not be drawn as a part.
    is_silent: bool = False
    max_onset_rate_per_bar: float = 0.0

    def is_active(self, t: float) -> bool:
        return any(s.start <= t < s.end for s in self.segments)

    def active_at(self, t: float) -> ActivitySegment | None:
        for s in self.segments:
            if s.start <= t < s.end:
                return s
        return None


