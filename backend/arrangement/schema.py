class LabelAlternative(BaseModel):
    """A label the labeller considered and how strongly it scored."""

    label: str
    score: float


class Section(BaseModel):
    id: str
    start: float
    end: float
    label: SectionLabel = SectionLabel.UNKNOWN
    label_confidence: float = 0.3
    label_source: Literal["model", "llm", "heuristic", "user"] = "heuristic"
    #: Deliberately a model, not a tuple. As ``list[tuple[str, float]]`` the
    #: writer emitted ``(score, label)``, JSON stored it as a two-element list,
    #: and every later reload failed validation with a type error. The order was
    #: wrong in the data and invisible in the type.
    label_alternatives: list[LabelAlternative] = Field(default_factory=list)

    # musical repetition
    repeat_group: int | None = None
    repeat_rank: int = 0
    similarity_to_primary: float = 0.0
    frame_start: int = 0
    frame_end: int = 0

    # --- macro structure -------------------------------------------------
    # A detected boundary is not a section. When several adjacent detected
    # segments turn out to share a name they are one formal section with an
    # internal change, and the section list should say so. `macro_id` groups
    # them; `macro_label` carries the numbered name a producer would use
    # ("Chorus 2"); `macro_index` is 1-based within the whole song.
    macro_id: str | None = None
    macro_label: str | None = None
    macro_index: int = 0
    macro_part: int = 0
    macro_parts: int = 1

    # summary stats
    bar_start: int | None = None
    bar_end: int | None = None
    energy_raw: float = 0.0
    energy_perceived: float = 0.0
    loudness_lufs: float | None = None
    source_count: int = 0
    source_ids: list[str] = Field(default_factory=list)
    stereo_width: float = 0.0
    stereo_correlation: float = 0.0
    density: float = 0.0
    dominant_source: str | None = None
    novelty: float = 0.0
    description: str | None = None  # LLM-written
    deltas_from_previous: list[str] = Field(default_factory=list)

    @property
    def dur(self) -> float:
        return max(0.0, self.end - self.start)


