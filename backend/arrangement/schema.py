"""The intermediate representation (IR) of a song.

This is the contract between four layers:

    DSP / models  ->  analysis  ->  reasoning (LLM)  ->  UI

Every number the language model is allowed to talk about must be able to trace
back to an :class:`Evidence` record.  Nothing in this module is generated by an
LLM except the explicitly-marked ``source="llm"`` fields.
"""

from __future__ import annotations

import math
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Primitives
# ---------------------------------------------------------------------------


class EvidenceStrength(str, Enum):
    """How directly the evidence supports the claim."""

    DIRECT = "direct"       # a measurement of the thing itself
    DERIVED = "derived"     # a deterministic function of measurements
    INFERRED = "inferred"   # a model prediction (e.g. a tagger's label)
    SPECULATIVE = "speculative"  # creative/producer-level interpretation


class EvidenceSource(str, Enum):
    DSP = "dsp"
    MODEL = "model"
    METADATA = "metadata"
    LLM = "llm"
    DERIVED = "derived"


class Evidence(BaseModel):
    """A citation: 'why do you believe that'."""

    kind: EvidenceSource
    method: str  # e.g. "demucs:htdemucs_6s", "pyloudnorm:BS.1770-4", "spatial:side_mid"
    metric: str | None = None  # e.g. "rms_db", "stereo_correlation"
    t0: float | None = None
    t1: float | None = None
    value: Any = None
    unit: str | None = None
    strength: EvidenceStrength = EvidenceStrength.DERIVED
    note: str | None = None  # human-readable, shown in the UI

    def summary(self) -> str:
        bits = [self.method]
        if self.metric:
            bits.append(self.metric)
        if self.t0 is not None:
            bits.append(f"t={self.t0:.2f}–{self.t1:.2f}s" if self.t1 else f"t={self.t0:.2f}s")
        if self.value is not None and not isinstance(self.value, (dict, list)):
            bits.append(f"={_fmt(self.value)}{self.unit or ''}")
        return " · ".join(str(b) for b in bits if b)


def _fmt(v: float) -> str:
    if isinstance(v, float):
        if abs(v) >= 100 or (v != 0 and abs(v) < 0.01):
            return f"{v:.3g}"
        return f"{v:.2f}"
    return str(v)


class Span(BaseModel):
    start: float
    end: float

    @property
    def dur(self) -> float:
        return max(0.0, self.end - self.start)

    def overlaps(self, other: "Span") -> bool:
        return self.start < other.end and other.start < self.end

    def contains(self, t: float) -> bool:
        return self.start <= t < self.end

    @staticmethod
    def of(a: float, b: float) -> "Span":
        return Span(start=min(a, b), end=max(a, b))


