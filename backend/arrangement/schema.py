class SongAnalysis(BaseModel):
    """Everything the app knows about one song."""

    schema_version: int = 3
    id: str
    source_path: str | None = None
    title: str
    artist: str | None = None
    album: str | None = None
    year: str | None = None
    duration: float = 0.0
    sample_rate: int = 44100
    channels: int = 2
    is_mono_source: bool = False
    source_quality: dict[str, Any] = Field(default_factory=dict)
    file_info: dict[str, Any] = Field(default_factory=dict)

    beats: BeatGrid = Field(default_factory=BeatGrid)
    loudness: Loudness = Field(default_factory=Loudness)
    energy: EnergyModel = Field(default_factory=EnergyModel)
    curves: CurveSet = Field(default_factory=CurveSet)
    spatial: SpatialCurve = Field(default_factory=SpatialCurve)
    harmony: HarmonySummary = Field(default_factory=HarmonySummary)

    sources: list[Source] = Field(default_factory=list)
    sections: list[Section] = Field(default_factory=list)
    transitions: list[SectionTransition] = Field(default_factory=list)
    events: list[ArrangementEvent] = Field(default_factory=list)
    energy_changes: list[EnergyChange] = Field(default_factory=list)

    separation: list[SourceSeparationInfo] = Field(default_factory=list)
    patterns: list[PatternFinding] = Field(default_factory=list)
    insights: list[Insight] = Field(default_factory=list)
    comparisons: list[ComparisonInsight] = Field(default_factory=list)

    novel_segments: list[Span] = Field(default_factory=list)
    fingerprint: dict[str, Any] = Field(default_factory=dict)
    metrics: dict[str, Any] = Field(default_factory=dict)

    quality: str = "standard"
    models_used: dict[str, str] = Field(default_factory=dict)
    stages: list[PipelineStage] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    created_at: float = 0.0
    analysis_version: str = "0.1.0"
    llm_enabled: bool = False

    # ---- lookups --------------------------------------------------------
    def source(self, source_id: str) -> Source | None:
        for s in self.sources:
            if s.id == source_id:
                return s
        return None

    def section(self, section_id: str) -> Section | None:
        for s in self.sections:
            if s.id == section_id:
                return s
        return None

    def section_at(self, t: float) -> Section | None:
        for s in self.sections:
            if s.start <= t < s.end:
                return s
        return None

    def event(self, event_id: str) -> ArrangementEvent | None:
        for e in self.events:
            if e.id == event_id:
                return e
        return None

    def active_sources(self, t: float) -> list[Source]:
        return [s for s in self.sources if s.is_active(t)]

    def nearest_event(self, t: float, max_dt: float = 2.0) -> ArrangementEvent | None:
        best, bd = None, max_dt
        for e in self.events:
            d = abs(e.t - t)
            if d < bd:
                best, bd = e, d
        return best

    def family_of(self, source_id: str) -> str:
        s = self.source(source_id)
        return s.family.value if s else "unknown"
