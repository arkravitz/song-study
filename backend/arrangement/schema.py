class Curve(BaseModel):
    """A named time series sampled on a uniform grid."""

    name: str
    frame_hz: float
    values: list[float]
    unit: str | None = None
    lo: float | None = None
    hi: float | None = None
    description: str | None = None

    def at(self, t: float) -> float:
        if not self.values:
            return float("nan")
        i = int(round(t * self.frame_hz))
        i = max(0, min(len(self.values) - 1, i))
        return self.values[i]

    def window(self, t0: float, t1: float) -> list[float]:
        i0 = max(0, int(round(t0 * self.frame_hz)))
        i1 = min(len(self.values), int(round(t1 * self.frame_hz)))
        return self.values[i0:i1]


class CurveSet(BaseModel):
    """All global curves, resampled onto one common grid."""

    frame_hz: float = 86.13
    duration: float = 0.0
    curves: dict[str, Curve] = Field(default_factory=dict)
    band_energy: dict[str, Curve] = Field(default_factory=dict)

    def get(self, name: str) -> Curve | None:
        return self.curves.get(name) or self.band_energy.get(name)

    def resample_stats(
        self, name: str, t0: float, t1: float, fn=min
    ) -> float | None:
        c = self.get(name)
        if c is None:
            return None
        vals = c.window(t0, t1)
        return float(fn(vals)) if vals else None


